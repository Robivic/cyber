// Mock local storage functions for demonstration
export const mockStorage = {
  newsletterSignups: JSON.parse(localStorage.getItem('newsletterSignups') || '[]'),
  prayerRequests: JSON.parse(localStorage.getItem('prayerRequests') || '[]'),
  donations: JSON.parse(localStorage.getItem('donations') || '[]'),
  
  addNewsletterSignup: (email) => {
    const signups = JSON.parse(localStorage.getItem('newsletterSignups') || '[]');
    signups.push({ email, date: new Date().toISOString() });
    localStorage.setItem('newsletterSignups', JSON.stringify(signups));
  },
  
  addPrayerRequest: (request) => {
    const requests = JSON.parse(localStorage.getItem('prayerRequests') || '[]');
    requests.push({ ...request, id: Date.now(), date: new Date().toISOString() });
    localStorage.setItem('prayerRequests', JSON.stringify(requests));
  },
  
  addDonation: (donation) => {
    const donations = JSON.parse(localStorage.getItem('donations') || '[]');
    donations.push({ ...donation, id: Date.now(), date: new Date().toISOString() });
    localStorage.setItem('donations', JSON.stringify(donations));
  }
};